@migration
def add_customers(conn):
    """A real customer record, separate from the flat customer_name/address/customer_email
    columns quotes have always carried directly -- lets Jim see every customer in one list
    and fix a phone/email typo once instead of per-quote. Deliberately keeps the flat quote
    columns as the read path (16 templates and ~9 routes read quote.customer_name/.address/
    .customer_email directly off a plain `SELECT * FROM quotes` row -- rewriting all of them
    to JOIN customers was a much larger, riskier diff for no real benefit, and duplicate
    column aliases are fragile under db_compat's sqlite3.Row-style wrapper anyway). Instead,
    customers is the write source of truth: _get_or_create_customer() links a quote to a
    customer on creation, and editing a customer's name/phone/email (from the new /customers
    page, or from a quote's own Edit Details) cascades that change to every quote linked to
    that customer_id. Address deliberately does NOT cascade -- a quote's address is the job
    site, which can legitimately differ across jobs for the same repeat customer (two
    properties), so quotes.address stays independently editable exactly as it always has.

    Backfill groups existing quotes by normalized (customer_name, address): same name and
    same address collapse to one customer; same name with a different address becomes two
    distinct customers, since guessing they're the same person risks merging two different
    people who share a name. This is a heuristic, not a perfect dedup -- expect a few near-
    duplicates from real-world name variations across old quotes, correctable by hand on the
    new Customers page."""
    c = conn.cursor()
    c.execute('''CREATE TABLE IF NOT EXISTS customers (
        customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        address TEXT DEFAULT '',
        email TEXT DEFAULT '',
        phone TEXT DEFAULT '',
        created_at TEXT DEFAULT (now()::text)
    )''')
    q_cols = {r[1] for r in c.execute("PRAGMA table_info(quotes)").fetchall()}
    if 'customer_id' not in q_cols:
        c.execute("ALTER TABLE quotes ADD COLUMN customer_id INTEGER")
        quotes = c.execute("SELECT quote_id, customer_name, address, customer_email FROM quotes").fetchall()
        seen = {}
        for q in quotes:
            key = ((q['customer_name'] or '').strip().lower(), (q['address'] or '').strip().lower())
            if key not in seen:
                cur = c.execute(
                    "INSERT INTO customers (name, address, email) VALUES (?,?,?) RETURNING customer_id",
                    ((q['customer_name'] or '').strip(), q['address'] or '', q['customer_email'] or ''))
                seen[key] = cur.fetchone()[0]
            c.execute("UPDATE quotes SET customer_id=? WHERE quote_id=?", (seen[key], q['quote_id']))
    conn.commit()


